/*
PURPOSE: Handles errors from asynchronous route handlers.

- Wraps async controller functions.
- Catches rejected Promises or errors.
- Passes errors to Express error-handling middleware using next(error).
- Avoids writing try-catch blocks in every async controller.
*/



const asyncHandler = (requestHandler) => {
    return (req, res, next) => {
        Promise.resolve(requestHandler(req, res, next)).catch((err) => next(err))
    }
}


export { asyncHandler }




